// Shared by the browser and the server (plain ES module, zero dependencies).

export const USDC_DECIMALS = 6;

/** "12.5" -> "12500000" (smallest units, as string). Throws on bad input. */
export function toUnits(input, decimals = USDC_DECIMALS) {
  const s = String(input).trim();
  if (!/^\d+(\.\d+)?$/.test(s)) throw new Error(`Invalid amount: "${input}"`);
  const [whole, frac = ""] = s.split(".");
  if (frac.length > decimals) throw new Error(`Too many decimals (max ${decimals}): "${input}"`);
  return (BigInt(whole) * 10n ** BigInt(decimals) + BigInt(frac.padEnd(decimals, "0") || "0")).toString();
}

/** "12500000" -> "12.50" (always at least 2 decimals, trims the rest). */
export function fromUnits(units, decimals = USDC_DECIMALS, minFrac = 2) {
  const n = BigInt(units);
  const neg = n < 0n;
  const abs = neg ? -n : n;
  const base = 10n ** BigInt(decimals);
  let frac = (abs % base).toString().padStart(decimals, "0").replace(/0+$/, "");
  if (frac.length < minFrac) frac = frac.padEnd(minFrac, "0");
  return `${neg ? "-" : ""}${(abs / base).toString()}${frac ? "." + frac : ""}`;
}

/** 1234567.5 -> "1,234,567.50" for display */
export function group(numStr) {
  const [w, f] = numStr.split(".");
  return w.replace(/\B(?=(\d{3})+(?!\d))/g, ",") + (f ? "." + f : "");
}

/** Deterministic JSON: keys sorted recursively. What gets signed and hashed. */
export function canonical(value) {
  if (Array.isArray(value)) return "[" + value.map(canonical).join(",") + "]";
  if (value && typeof value === "object") {
    return "{" + Object.keys(value).sort().map((k) => JSON.stringify(k) + ":" + canonical(value[k])).join(",") + "}";
  }
  return JSON.stringify(value);
}

/** Line items -> total in smallest units. qty may be fractional (e.g. 1.5 hours). */
export function invoiceTotal(items) {
  let total = 0n;
  for (const it of items) {
    const unit = BigInt(toUnits(it.unit_price));
    const qty = String(it.qty);
    if (!/^\d+(\.\d{1,3})?$/.test(qty)) throw new Error(`Invalid quantity: "${it.qty}"`);
    const [qw, qf = ""] = qty.split(".");
    const milli = BigInt(qw) * 1000n + BigInt(qf.padEnd(3, "0") || "0");
    total += (unit * milli) / 1000n;
  }
  return total.toString();
}

export const HEX64 = /^[0-9a-f]{64}$/;

const ID_ALPHABET = "23456789ABCDEFGHJKMNPQRSTUVWXYZ";
/** "K7QM-2XPD": generated by the freelancer's browser so the id is inside the signed call. */
export function makeInvoiceId(randomBytes) {
  let s = "";
  for (const b of randomBytes.slice(0, 8)) s += ID_ALPHABET[b % ID_ALPHABET.length];
  return `${s.slice(0, 4)}-${s.slice(4)}`;
}

/** The exact object whose sha256 is stored on-chain as memo_hash. */
export function memoPayload({ id, owner, client_name, title, items, due_date, note }) {
  return {
    id, owner, client_name, title, due_date, note: note || "", currency: "USDC",
    items: items.map((i) => ({ description: i.description, qty: String(i.qty), unit_price: String(i.unit_price) })),
    total: invoiceTotal(items),
  };
}

